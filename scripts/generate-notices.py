#!/usr/bin/env python3
"""Generate THIRD-PARTY-NOTICES.md from the actual dependency trees.

Covers everything that ships in a compiled release:
- Rust crates from `cargo license --json` (the binary statically links them all)
- Frontend packages from package.json "dependencies" (bundled into the assets)

Dev-only tooling (Vite, TypeScript, vue-tsc, cargo dev-deps) never ships, so
it is deliberately excluded.

License texts are fetched from the SPDX license list at generation time, so the
committed output is self-contained for binary distribution. Run from the repo
root:

    python3 scripts/generate-notices.py
"""

import json
import re
import subprocess
import sys
import urllib.request
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "THIRD-PARTY-NOTICES.md"

# npm packages that end up bundled into the shipped frontend assets, with
# their verified licenses (lockfiles don't carry license info).
NPM_PACKAGES = [
    ("vue", "MIT", "https://github.com/vuejs/core"),
    ("@tauri-apps/api", "MIT OR Apache-2.0", "https://github.com/tauri-apps/tauri"),
    ("@tauri-apps/plugin-dialog", "MIT OR Apache-2.0", "https://github.com/tauri-apps/plugins-workspace"),
    ("@tauri-apps/plugin-opener", "MIT OR Apache-2.0", "https://github.com/tauri-apps/plugins-workspace"),
]

# SPDX ids this project's trees are known to use, plus license exceptions.
KNOWN_IDS = [
    "0BSD", "Apache-2.0", "BSD-2-Clause", "BSD-3-Clause", "CC0-1.0",
    "CDLA-Permissive-2.0", "ISC", "MIT", "MIT-0", "MPL-2.0",
    "Unicode-3.0", "Unlicense", "Zlib",
]
KNOWN_EXCEPTIONS = ["LLVM-exception"]

ID_RE = re.compile(r"\b(" + "|".join(re.escape(i) for i in KNOWN_IDS) + r")\b")
EXC_RE = re.compile(r"\b(" + "|".join(re.escape(e) for e in KNOWN_EXCEPTIONS) + r")\b")

# Human labels for license sections, in display order.
LABELS = {
    "0BSD": "0BSD (Zero-clause BSD)",
    "Apache-2.0": "Apache License 2.0",
    "BSD-2-Clause": "BSD 2-Clause",
    "BSD-3-Clause": "BSD 3-Clause",
    "CC0-1.0": "CC0 1.0 Universal",
    "CDLA-Permissive-2.0": "Community Data License Agreement (Permissive) 2.0",
    "ISC": "ISC License",
    "MIT": "MIT License",
    "MIT-0": "MIT No Attribution",
    "MPL-2.0": "Mozilla Public License 2.0",
    "Unicode-3.0": "Unicode License v3",
    "Unlicense": "The Unlicense",
    "Zlib": "zlib License",
}

SELF_CRATE = "noground"


def cargo_deps() -> list[dict]:
    out = subprocess.run(
        ["cargo", "license", "--json"],
        cwd=ROOT / "src-tauri", capture_output=True, text=True, check=True,
    ).stdout
    rows = json.loads(out)
    return [r for r in rows if r["name"] != SELF_CRATE]


def npm_versions() -> dict[str, str]:
    lock = json.loads((ROOT / "package-lock.json").read_text())
    pkgs = lock.get("packages", {})
    versions = {}
    for key, meta in pkgs.items():
        m = re.fullmatch(r"node_modules/(.+)", key)
        if m and "version" in meta:
            versions[m.group(1)] = meta["version"]
    return versions


def license_ids(expression: str) -> list[str]:
    ids = list(dict.fromkeys(ID_RE.findall(expression or "")))
    return ids or ["UNKNOWN"]


def spdx_text(spdx_id: str) -> str:
    url = f"https://spdx.org/licenses/{spdx_id}.json"
    with urllib.request.urlopen(url) as resp:
        data = json.loads(resp.read())
    # license exceptions carry their text under a different key
    return data.get("licenseText") or data.get("licenseExceptionText", "")


def main() -> None:
    crates = cargo_deps()
    npm_versions_map = npm_versions()

    # crates under each license id / exception
    by_id: dict[str, list[str]] = defaultdict(list)
    for r in crates:
        entry = f"{r['name']} {r['version']}"
        for i in license_ids(r["license"]):
            by_id[i].append(entry)
    npm_by_id: dict[str, list[str]] = defaultdict(list)
    for name, lic, _url in NPM_PACKAGES:
        ver = npm_versions_map.get(name, "?")
        for i in license_ids(lic):
            npm_by_id[i].append(f"{name} {ver}")

    exceptions = sorted({e for r in crates for e in EXC_RE.findall(r["license"] or "")})
    ids = sorted(by_id | npm_by_id, key=lambda i: (len(by_id[i] or npm_by_id[i]), i), reverse=True)

    lines: list[str] = []
    lines.append("# Third-party notices\n")
    lines.append("This file covers the third-party components incorporated in Noground when it "
                 "is distributed in compiled form: all Rust crates are statically linked into the "
                 "binary, and the frontend packages listed here are bundled into the application "
                 "assets. Build-time-only tooling (Vite, TypeScript, vue-tsc, cargo dev/build "
                 "dependencies) is not distributed and is not listed.\n")
    lines.append("Generated by `scripts/generate-notices.py` — do not edit by hand; "
                 "re-run the script after changing dependencies.\n")

    lines.append("## Rust crates\n")
    lines.append(f"{len(crates)} crates. Multiple entries per crate reflect "
                 "dual/triple licensing (you may rely on any one of the listed licenses).\n")
    for i in ids:
        deps = sorted(set(by_id.get(i, [])))
        if not deps:
            continue
        lines.append(f"### {LABELS.get(i, i)} ({len(deps)} crates)\n")
        lines.append("<details><summary>crate list</summary>\n")
        lines.append("```")
        lines.extend(deps)
        lines.append("```\n")
        lines.append("</details>\n")

    lines.append("## Frontend packages\n")
    for name, lic, url in NPM_PACKAGES:
        lines.append(f"- [{name}]({url}) {npm_versions_map.get(name, '?')} — {lic}")
    lines.append("")

    if exceptions:
        lines.append("## License exceptions\n")
        lines.append("The following exceptions apply to crates carrying them "
                     "(in addition to the license texts below):\n")
        for e in exceptions:
            lines.append(f"### {e}\n")
            lines.append(spdx_text(e) + "\n")

    lines.append("## License texts\n")
    for i in ids:
        lines.append(f"### {LABELS.get(i, i)}\n")
        lines.append("```")
        lines.append(spdx_text(i).strip())
        lines.append("```\n")

    OUT.write_text("\n".join(lines))
    n_ids = len(ids)
    print(f"wrote {OUT} ({n_ids} license ids, {len(crates)} crates, {len(NPM_PACKAGES)} npm packages)")


if __name__ == "__main__":
    sys.exit(main())
